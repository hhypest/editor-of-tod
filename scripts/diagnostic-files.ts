/** Build-time source allowlist. Never inspect the user's filesystem at runtime. */
import { existsSync, lstatSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const manifest = 'src/shared/diagnostic-files.generated.ts'
const sourceFile = /\.(?:ts|tsx|mts|mjs|cjs|vue)$/
const testFile = /(?:\.(?:test|spec)\.[^.]+|\.d\.ts)$/

export function diagnosticProgramFiles(root: string): string[] {
  // server/store.ts is the retired facade, retained for already stored diagnostic events.
  const files = new Set(['server.cjs', 'server/store.ts'])
  function visit(directory: string) {
    const absolute = join(root, directory)
    if (!existsSync(absolute) || !lstatSync(absolute).isDirectory()) return
    for (const entry of readdirSync(absolute, { withFileTypes: true })) {
      if (entry.name.startsWith('.') || entry.name === '__tests__' || entry.name === 'node_modules')
        continue
      const path = `${directory}/${entry.name}`
      if (entry.isDirectory()) visit(path)
      // Dirents deliberately reject symlinks; arbitrary files and private-data are never walked.
      else if (
        entry.isFile() &&
        sourceFile.test(entry.name) &&
        !testFile.test(entry.name) &&
        path !== manifest &&
        /^[A-Za-z0-9_./-]+$/.test(path)
      )
        files.add(path)
    }
  }
  for (const directory of ['src', 'server', 'scripts']) visit(directory)
  return [...files].sort()
}

export function renderDiagnosticFiles(root: string): string {
  return (
    '// Generated by scripts/diagnostic-files.ts at build time. Do not edit by hand.\n' +
    'export const diagnosticProgramFiles = [\n' +
    diagnosticProgramFiles(root)
      .map((path) => `  '${path}',\n`)
      .join('') +
    '] as const\n'
  )
}

/** Keep the checked-in manifest usable for direct Node source execution as well as bundles. */
export function writeDiagnosticFiles(root: string, check = false): void {
  const target = join(root, manifest)
  const expected = renderDiagnosticFiles(root)
  const actual = existsSync(target) ? readFileSync(target, 'utf8') : ''
  if (actual === expected) return
  if (check) throw new Error('Список диагностики устарел: node scripts/diagnostic-files.ts')
  writeFileSync(target, expected)
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href)
  writeDiagnosticFiles(
    fileURLToPath(new URL('..', import.meta.url)),
    process.argv.includes('--check'),
  )
