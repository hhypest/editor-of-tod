/**
 * Число для надписей листа: десятичная запятая, как принято в документах на русском языке.
 * Строка из карточки ПУ-66 («6.5») оформляется так же; прочий текст не меняется.
 */
export function decimalComma(value: number | string): string {
  return String(value).replace(/(\d)\.(?=\d)/g, '$1,')
}
