/** Раздел справки для экрана, с которого её открыли. */
export function helpSectionFor(view: string, registryTab?: string): string {
  if (view === 'registries') {
    return (
      {
        imports: 'signs',
        documents: 'documents',
        parameters: 'parameters',
        entries: 'backup',
        diagnostics: 'diagnostics',
      }[registryTab ?? ''] ?? 'first-run'
    )
  }
  return (
    {
      projects: 'new-project',
      source: 'stage-source',
      geometry: 'stage-geometry',
      objects: 'stage-objects',
      review: 'stage-review',
    }[view] ?? 'overview'
  )
}

/** Текст раздела без разметки подписей: для поиска. */
export function sectionText(section: HelpSection): string {
  const parts: string[] = [section.title]
  for (const block of section.blocks) {
    if ('p' in block) parts.push(block.p)
    else if ('note' in block) parts.push(block.note)
    else if ('warn' in block) parts.push(block.warn)
    else if ('steps' in block) parts.push(...block.steps)
    else if ('list' in block) parts.push(...block.list)
    else if ('table' in block) parts.push(...block.table.head, ...block.table.rows.flat())
    else parts.push(...block.terms.flat())
  }
  return parts.join(' ').replace(/\[\[|\]\]/g, '')
}

function normalize(text: string): string {
  return text.toLocaleLowerCase('ru-RU').replace(/ё/g, 'е')
}

/** Разделы, в тексте которых есть все слова запроса. */
export function searchHelp(query: string, sections = helpSections): HelpSection[] {
  const words = normalize(query).split(/\s+/).filter(Boolean)
  if (!words.length) return sections
  return sections.filter((section) => {
    const text = normalize(sectionText(section))
    return words.every((word) => text.includes(word))
  })
}

/** Текст с разметкой подписей: [[Подпись]] → части для отображения. */
export function splitLabels(text: string): Array<{ text: string; label: boolean }> {
  return text
    .split(/(\[\[[^\]]+\]\])/)
    .filter(Boolean)
    .map((part) =>
      part.startsWith('[[')
        ? { text: part.slice(2, -2), label: true }
        : { text: part, label: false },
    )
}

/** Все подписи интерфейса, упомянутые в справке. */
export function helpLabels(sections = helpSections): string[] {
  const labels = new Set<string>()
  const collect = (text: string) => {
    for (const part of splitLabels(text)) if (part.label) labels.add(part.text)
  }
  for (const section of sections) {
    for (const block of section.blocks) {
      if ('p' in block) collect(block.p)
      else if ('note' in block) collect(block.note)
      else if ('warn' in block) collect(block.warn)
      else if ('steps' in block) block.steps.forEach(collect)
      else if ('list' in block) block.list.forEach(collect)
      else if ('table' in block) block.table.rows.flat().forEach(collect)
    }
  }
  return [...labels]
}
